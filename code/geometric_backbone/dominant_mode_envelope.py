def build_a0_policy_from_iep_model(iep_model, static_pool, config=None):
    """Build A0Policy from the frozen hfss_sr_sparse v2 IEPModel interface.

    IEPModel.a0_abs() accepts theta in radians, so this adapter requires and
    records a0_input_unit='rad' to prevent a silent degree/radian mismatch.
    """
    if getattr(iep_model, "schema_name", None) != "hfss_sr_sparse":
        raise ValueError("dominant_mode_envelope requires schema_name='hfss_sr_sparse'")
    if int(getattr(iep_model, "schema_version", -1)) != 2:
        raise ValueError("dominant_mode_envelope requires schema_version=2")
    if getattr(iep_model, "spectral_frame", None) != "sr_compatible_sparse_v2":
        raise ValueError("dominant_mode_envelope requires spectral_frame='sr_compatible_sparse_v2'")

    ready = iep_model.validate_stage1_ready(require_sr_compatible=True)
    if not bool(ready.get("ok", False)):
        raise ValueError("IEP model is not Stage1-ready: %s" % ready.get("issues", []))

    if config is None:
        config = A0PolicyConfig(a0_input_unit="rad")
    if config.a0_input_unit != "rad":
        raise ValueError("IEPModel.a0_abs requires A0PolicyConfig(a0_input_unit='rad')")

    theta_probe = np.asarray([0.0, 0.5 * math.pi], dtype=np.float64)
    a0_probe = np.asarray(iep_model.a0_abs(theta_probe), dtype=np.float64)
    if a0_probe.shape != theta_probe.shape or np.any(~np.isfinite(a0_probe)):
        raise ValueError("IEPModel.a0_abs failed the finite 0-to-90-degree probe")

    summary = iep_model.summary()
    iep_metadata = {
        "schema_name": summary.get("schema_name"),
        "schema_version": summary.get("schema_version"),
        "spectral_frame": summary.get("spectral_frame"),
        "co_handedness": summary.get("co_handedness"),
        "cx_handedness": summary.get("cx_handedness"),
        "spin_sign": summary.get("spin_sign"),
        "cp_basis_sign": summary.get("cp_basis_sign"),
        "npz_path": summary.get("npz_path"),
        "json_path": summary.get("meta_json_path"),
        "npz_sha256": summary.get("npz_sha256"),
        "source_csv_path": summary.get("source_csv_path"),
        "source_csv_sha256": summary.get("source_csv_sha256"),
        "normalization_A_ref": summary.get("normalization_A_ref"),
        "normalization_scale": summary.get("normalization_scale"),
        "cx_fit_validated_theta_max_deg": summary.get("cx_fit_validated_theta_max_deg"),
    }
    return A0Policy(
        a0_abs_fn=iep_model.a0_abs,
        static_pool=static_pool,
        config=config,
        iep_metadata=iep_metadata,
    )


