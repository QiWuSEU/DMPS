class A0Policy:
    def __init__(
        self,
        a0_abs_fn: Callable[[np.ndarray], np.ndarray],
        static_pool: StaticPoolSnapshot,
        config: A0PolicyConfig = A0PolicyConfig(),
        iep_metadata: Optional[Mapping[str, Any]] = None,
    ) -> None:
        if config.a0_input_unit not in ("deg", "rad"):
            raise ValueError("config.a0_input_unit must be 'deg' or 'rad'")
        if config.score_mode != "product":
            raise ValueError("only score_mode='product' is currently supported")

        self.a0_abs_fn = a0_abs_fn
        self.static_pool = static_pool
        self.config = config
        self.iep_metadata = dict(iep_metadata or {})

        self.theta_cache_deg: Optional[np.ndarray] = None
        self.a0_cache_abs: Optional[np.ndarray] = None

        self.global_monotone_decreasing: Optional[bool] = None
        self.global_monotone_report: Optional[MonotonicityReport] = None

        self.scan_monotone_map: Dict[float, bool] = {}
        self.scan_monotone_reports: Dict[float, MonotonicityReport] = {}

        self.core_a0_max_cache: Dict[float, np.ndarray] = {}
        self.core_build_reports: Dict[float, CoreEnvelopeBuildReport] = {}

        pool_meta_check = self.static_pool.validate_static_pool_metadata()
        if not bool(pool_meta_check.get("ok", False)):
            self._log(f"[warn][static_pool_metadata] {pool_meta_check}")

    def _log(self, msg: str) -> None:
        if self.config.verbose:
            print(msg)

    # ------------------------------------------------------------------
    # Low-level |a0| evaluation and cache (theta cache is in degrees)
    # ------------------------------------------------------------------
    def _coerce_theta_deg(self, theta_deg: Union[np.ndarray, Sequence[float], float]) -> np.ndarray:
        arr = np.asarray(theta_deg, dtype=np.float64)
        return np.clip(arr, self.config.theta_min_deg, self.config.theta_max_deg)

    def _eval_a0_abs_raw(self, theta_deg: Union[np.ndarray, Sequence[float], float]) -> np.ndarray:
        theta_deg_arr = self._coerce_theta_deg(theta_deg)
        if self.config.a0_input_unit == "deg":
            x = theta_deg_arr
        else:
            x = np.deg2rad(theta_deg_arr)
        y = np.asarray(self.a0_abs_fn(x), dtype=np.float64)
        if y.shape != theta_deg_arr.shape:
            y = np.asarray(np.broadcast_to(y, theta_deg_arr.shape), dtype=np.float64)
        if not np.all(np.isfinite(y)):
            raise ValueError("a0_abs_fn returned non-finite values")
        return y

    def build_theta_cache(self, force_rebuild: bool = False) -> None:
        if self.theta_cache_deg is not None and self.a0_cache_abs is not None and not force_rebuild:
            return
        step = float(self.config.theta_cache_step_deg)
        self.theta_cache_deg = np.arange(self.config.theta_min_deg, self.config.theta_max_deg + 0.5 * step, step, dtype=np.float64)
        self.theta_cache_deg = np.clip(self.theta_cache_deg, self.config.theta_min_deg, self.config.theta_max_deg)
        self.theta_cache_deg = np.unique(np.round(self.theta_cache_deg, 12))
        self.a0_cache_abs = self._eval_a0_abs_raw(self.theta_cache_deg)
        self._log("=== DOMINANT MODE ENVELOPE: BUILD THETA CACHE ===")
        self._log(f"[cache] theta range=[{self.theta_cache_deg[0]:.3f},{self.theta_cache_deg[-1]:.3f}] deg step={step} count={self.theta_cache_deg.size}")
        self._log(f"[cache] a0 min/mean/max = {self.a0_cache_abs.min():.6g} / {self.a0_cache_abs.mean():.6g} / {self.a0_cache_abs.max():.6g}")

    def _interp_a0_abs_from_cache(self, theta_deg: Union[np.ndarray, Sequence[float], float]) -> np.ndarray:
        self.build_theta_cache()
        assert self.theta_cache_deg is not None and self.a0_cache_abs is not None
        theta = self._coerce_theta_deg(theta_deg)
        y = np.interp(theta, self.theta_cache_deg, self.a0_cache_abs)
        return np.asarray(y, dtype=np.float64)

    # ------------------------------------------------------------------
    # Monotonicity tests
    # ------------------------------------------------------------------
    def _test_monotone_decreasing_on_interval(self, theta_lo_deg: float, theta_hi_deg: float) -> MonotonicityReport:
        theta_lo_deg = max(self.config.theta_min_deg, float(theta_lo_deg))
        theta_hi_deg = min(self.config.theta_max_deg, float(theta_hi_deg))
        if theta_hi_deg < theta_lo_deg:
            theta_hi_deg = theta_lo_deg
        step = float(self.config.mono_test_step_deg)
        grid = np.arange(theta_lo_deg, theta_hi_deg + 0.5 * step, step, dtype=np.float64)
        grid = np.unique(np.round(np.concatenate([grid, [theta_lo_deg, theta_hi_deg]]), 12))
        vals = self._interp_a0_abs_from_cache(grid)
        dv = vals[1:] - vals[:-1]
        tol = np.maximum(self.config.mono_abs_tol, self.config.mono_rel_tol * np.maximum(vals[:-1], 1e-15))
        bad = dv > tol
        violation_count = int(np.count_nonzero(bad))
        worst_positive_jump = float(np.max(np.where(bad, dv, 0.0))) if dv.size > 0 else 0.0
        report = MonotonicityReport(
            theta_lo_deg=float(theta_lo_deg),
            theta_hi_deg=float(theta_hi_deg),
            n_samples=int(grid.size),
            is_monotone_decreasing=(violation_count == 0),
            violation_count=violation_count,
            worst_positive_jump=worst_positive_jump,
        )
        return report

    def test_global_monotone_decreasing(self, force_retest: bool = False) -> bool:
        if self.global_monotone_decreasing is not None and not force_retest:
            return bool(self.global_monotone_decreasing)
        report = self._test_monotone_decreasing_on_interval(self.config.theta_min_deg, self.config.theta_max_deg)
        self.global_monotone_decreasing = bool(report.is_monotone_decreasing)
        self.global_monotone_report = report
        self._log("=== DOMINANT MODE ENVELOPE: GLOBAL MONOTONICITY TEST ===")
        self._log(str(asdict(report)))
        return bool(self.global_monotone_decreasing)

    def _core_theta_interval_for_scan(self, theta_s_deg: float, mode: str = "work") -> Tuple[float, float]:
        core_pts = self.static_pool.get_core_points(float(theta_s_deg), mode=mode)
        theta_min = np.asarray(core_pts["theta_min_deg"], dtype=np.float64)
        theta_max = np.asarray(core_pts["theta_max_deg"], dtype=np.float64)
        if theta_min.size == 0 or theta_max.size == 0:
            raise ValueError(f"no core points for theta_s={theta_s_deg} mode={mode}")
        return float(np.min(theta_min)), float(np.max(theta_max))

    def test_scan_monotone_decreasing(self, theta_s_deg: float, mode: str = "work", force_retest: bool = False) -> bool:
        theta_s_deg = float(theta_s_deg)
        if theta_s_deg in self.scan_monotone_map and not force_retest:
            return bool(self.scan_monotone_map[theta_s_deg])
        theta_lo, theta_hi = self._core_theta_interval_for_scan(theta_s_deg, mode=mode)
        report = self._test_monotone_decreasing_on_interval(theta_lo, theta_hi)
        self.scan_monotone_map[theta_s_deg] = bool(report.is_monotone_decreasing)
        self.scan_monotone_reports[theta_s_deg] = report
        self._log(f"=== DOMINANT MODE ENVELOPE: SCAN MONOTONICITY TEST theta_s={theta_s_deg:.3f} deg mode={mode} ===")
        self._log(str(asdict(report)))
        return bool(report.is_monotone_decreasing)

    # ------------------------------------------------------------------
    # Conservative core envelope: endpoint maximum if monotone, otherwise
    # the maximum sampled over each theta interval.
    # ------------------------------------------------------------------
    def _interval_max_a0_abs(self, theta_lo_deg: float, theta_hi_deg: float, assume_monotone_decreasing: bool = False) -> float:
        theta_lo_deg = max(self.config.theta_min_deg, float(theta_lo_deg))
        theta_hi_deg = min(self.config.theta_max_deg, float(theta_hi_deg))
        if theta_hi_deg < theta_lo_deg:
            theta_hi_deg = theta_lo_deg
        if assume_monotone_decreasing:
            return float(self._interp_a0_abs_from_cache(np.asarray([theta_lo_deg], dtype=np.float64))[0])

        step = float(self.config.interval_sample_step_deg)
        grid = np.arange(theta_lo_deg, theta_hi_deg + 0.5 * step, step, dtype=np.float64)
        grid = np.unique(np.round(np.concatenate([grid, [theta_lo_deg, theta_hi_deg]]), 12))
        vals = self._interp_a0_abs_from_cache(grid)
        return float(np.max(vals))

    def build_core_a0_max_cache(
        self,
        scan_angles_deg: Optional[np.ndarray] = None,
        mode: str = "work",
        force_rebuild: bool = False,
    ) -> None:
        self.build_theta_cache()
        if scan_angles_deg is None:
            scan_angles_deg = self.static_pool.get_scan_angles(mode=mode)
        for theta_s_deg in np.asarray(scan_angles_deg, dtype=np.float64).tolist():
            theta_s_deg = float(theta_s_deg)
            if theta_s_deg in self.core_a0_max_cache and not force_rebuild:
                continue

            global_mono = self.test_global_monotone_decreasing(force_retest=False)
            if global_mono:
                mono = True
            else:
                mono = self.test_scan_monotone_decreasing(theta_s_deg, mode=mode, force_retest=force_rebuild)

            core_pts = self.static_pool.get_core_points(theta_s_deg, mode=mode)
            theta_min = np.asarray(core_pts["theta_min_deg"], dtype=np.float64)
            theta_max = np.asarray(core_pts["theta_max_deg"], dtype=np.float64)
            out = np.zeros_like(theta_min, dtype=np.float64)
            for i in range(theta_min.size):
                out[i] = self._interval_max_a0_abs(theta_min[i], theta_max[i], assume_monotone_decreasing=mono)

            self.core_a0_max_cache[theta_s_deg] = out
            strategy = "endpoint_max" if mono else "sampled_interval_max"
            report = CoreEnvelopeBuildReport(theta_s_deg=theta_s_deg, n_points=int(out.size), monotone_used=bool(mono), strategy=strategy)
            self.core_build_reports[theta_s_deg] = report
            self._log(f"=== DOMINANT MODE ENVELOPE: BUILD CORE ENVELOPE theta_s={theta_s_deg:.3f} deg ===")
            self._log(str(asdict(report)))
            self._log(f"[core_a0_max] min/mean/max = {out.min():.6g} / {out.mean():.6g} / {out.max():.6g}")

    def get_core_a0_max(self, theta_s_deg: float) -> np.ndarray:
        theta_s_deg = float(theta_s_deg)
        if theta_s_deg not in self.core_a0_max_cache:
            self.build_core_a0_max_cache(scan_angles_deg=np.asarray([theta_s_deg], dtype=np.float64), force_rebuild=False)
        return self.core_a0_max_cache[theta_s_deg].copy()

    # ------------------------------------------------------------------
    # 2D pointwise |a0| and score; the q=0 coefficient depends on theta only.
    # ------------------------------------------------------------------
    def eval_pointwise_a0(self, theta_deg: Union[np.ndarray, Sequence[float], float], phi_deg: Optional[Union[np.ndarray, Sequence[float], float]] = None) -> np.ndarray:
        # phi retained in signature for future full-2D EF extension; currently ignored.
        del phi_deg
        return self._interp_a0_abs_from_cache(theta_deg)

    def eval_pool_points_a0(self, points_2d: Mapping[str, np.ndarray]) -> np.ndarray:
        theta_deg = np.asarray(points_2d["theta_deg"], dtype=np.float64)
        phi_deg = np.asarray(points_2d["phi_deg"], dtype=np.float64) if "phi_deg" in points_2d else None
        out = self.eval_pointwise_a0(theta_deg, phi_deg)
        self._log(f"[2d_a0] n={out.size} min/mean/max = {out.min():.6g} / {out.mean():.6g} / {out.max():.6g}")
        return out

    def score_2d_points(self, af_abs: np.ndarray, points_2d: Mapping[str, np.ndarray]) -> np.ndarray:
        af_abs = np.asarray(af_abs, dtype=np.float64)
        a0_abs = self.eval_pool_points_a0(points_2d)
        if af_abs.shape != a0_abs.shape:
            raise ValueError(f"af_abs shape {af_abs.shape} does not match pool-point a0 shape {a0_abs.shape}")
        score = a0_abs * af_abs
        self._log(f"[2d_score] n={score.size} min/mean/max = {score.min():.6g} / {score.mean():.6g} / {score.max():.6g}")
        return score

    # ------------------------------------------------------------------
    # Debug summary export
    # ------------------------------------------------------------------
    def export_debug_summary(self, path: str) -> None:
        payload = {
            "config": asdict(self.config),
            "iep_source": dict(self.iep_metadata),
            "static_pool_metadata_check": self.static_pool.validate_static_pool_metadata(),
            "static_pool_partition_info": self.static_pool.get_partition_info(),
            "static_pool_partition_definition": self.static_pool.get_partition_definition(),
            "static_pool_config_core": {
                "alpha_core_max_deg": self.static_pool.get_alpha_core_max_deg(),
                "alpha_outer_start_deg": self.static_pool.get_alpha_outer_start_deg(),
                "buffer_ring_list_deg": self.static_pool.get_buffer_ring_list_deg().tolist(),
            },
            "global_monotone_decreasing": self.global_monotone_decreasing,
            "global_monotone_report": None if self.global_monotone_report is None else asdict(self.global_monotone_report),
            "scan_monotone_map": {f"{k:.6f}": bool(v) for k, v in self.scan_monotone_map.items()},
            "scan_monotone_reports": {f"{k:.6f}": asdict(v) for k, v in self.scan_monotone_reports.items()},
            "core_build_reports": {f"{k:.6f}": asdict(v) for k, v in self.core_build_reports.items()},
            "core_cache_keys_deg": [float(k) for k in sorted(self.core_a0_max_cache.keys())],
        }
        with open(path, "w", encoding="utf-8") as f:
            json.dump(payload, f, ensure_ascii=False, indent=2)
        self._log(f"[saved] dominant-mode envelope debug summary -> {path}")


