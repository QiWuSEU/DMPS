class StaticPoolSnapshot:
    """
    Lightweight view of the NPZ/JSON generated by geometric_sampling_pool.py.

    Serialized field names are intentionally unchanged for existing datasets.

    Supports both:
    1) original split format
       - core_full_*, core_work_*
       - buffer_full_*, buffer_work_*
       - outer_full_*, outer_work_*
    2) flat/runtime format
       - core_*, buffer_*, outer_*
    """

    def __init__(
        self,
        *,
        npz_data: Mapping[str, np.ndarray],
        summary: Mapping[str, Any],
    ) -> None:
        self._npz = {k: np.asarray(v) for k, v in npz_data.items()}
        self.summary = dict(summary)
        self.theta_s_full_deg = np.asarray(self._npz["theta_s_full_deg"], dtype=np.float64)
        self.theta_s_work_init_deg = np.asarray(self._npz["theta_s_work_init_deg"], dtype=np.float64)
        self._full_set = set(np.round(self.theta_s_full_deg, 12).tolist())
        self._work_set = set(np.round(self.theta_s_work_init_deg, 12).tolist())

        if "core_full_theta_s_deg" in self._npz:
            self._format = "split"
        elif "core_theta_s_deg" in self._npz or "core_scan_idx" in self._npz:
            self._format = "flat"
        else:
            raise KeyError(
                "Unrecognized pool npz format: expected 'core_full_theta_s_deg' "
                "or 'core_theta_s_deg'/'core_scan_idx'."
            )

    @classmethod
    def from_files(cls, npz_path: str, json_path: str) -> "StaticPoolSnapshot":
        with np.load(npz_path, allow_pickle=False) as d:
            npz_data = {k: np.asarray(d[k]) for k in d.files}
        with open(json_path, "r", encoding="utf-8") as f:
            summary = json.load(f)
        return cls(npz_data=npz_data, summary=summary)

    def get_scan_angles(self, mode: str = "full") -> np.ndarray:
        if mode == "full":
            return self.theta_s_full_deg.copy()
        if mode == "work":
            return self.theta_s_work_init_deg.copy()
        raise ValueError("mode must be 'full' or 'work'")

    def get_tracking_protocol(self) -> Dict[str, Any]:
        return dict(self.summary.get("tracking_protocol", {}))

    def get_pool_config(self) -> Dict[str, Any]:
        return dict(self.summary.get("config", {}))

    def get_partition_info(self) -> Dict[str, Any]:
        return dict(self.summary.get("partition_info", {}))

    def get_partition_definition(self) -> Dict[str, Any]:
        return dict(self.summary.get("partition_definition", {}))

    def get_alpha_core_max_deg(self) -> float:
        cfg = self.get_pool_config()
        if "alpha_core_max_deg" not in cfg:
            raise KeyError("summary.config.alpha_core_max_deg not found")
        return float(cfg["alpha_core_max_deg"])

    def get_alpha_outer_start_deg(self) -> float:
        cfg = self.get_pool_config()
        if "alpha_outer_start_deg" in cfg:
            return float(cfg["alpha_outer_start_deg"])
        return 90.0

    def get_buffer_ring_list_deg(self) -> np.ndarray:
        cfg = self.get_pool_config()
        vals = cfg.get("buffer_ring_list_deg", [])
        return np.asarray(vals, dtype=np.float64)

    def validate_static_pool_metadata(self) -> Dict[str, Any]:
        cfg = self.get_pool_config()
        pinfo = self.get_partition_info()
        issues: List[str] = []

        alpha_core = cfg.get("alpha_core_max_deg", None)
        if alpha_core is None:
            issues.append("missing config.alpha_core_max_deg")

        if pinfo:
            used = pinfo.get("alpha_core_used_deg", None)
            if used is not None and alpha_core is not None:
                if abs(float(used) - float(alpha_core)) > 1e-9:
                    issues.append(
                        f"partition alpha_core_used_deg={used} != config alpha_core_max_deg={alpha_core}"
                    )

        return {
            "ok": len(issues) == 0,
            "issues": issues,
            "format": self._format,
            "alpha_core_max_deg": None if alpha_core is None else float(alpha_core),
            "alpha_outer_start_deg": self.get_alpha_outer_start_deg(),
            "partition_mode": pinfo.get("mode", "unknown") if pinfo else "missing",
        }

    def _subset_split(self, prefix: str, theta_s_deg: float, mode: str) -> Dict[str, np.ndarray]:
        theta_key = f"{prefix}_{mode}_theta_s_deg"
        if theta_key not in self._npz:
            raise KeyError(f"Missing key in split pool format: {theta_key}")
        mask = np.isclose(np.asarray(self._npz[theta_key], dtype=np.float64), theta_s_deg, atol=1e-9)
        out: Dict[str, np.ndarray] = {}
        stem = f"{prefix}_{mode}_"
        for key, arr in self._npz.items():
            if key.startswith(stem):
                out[key[len(stem):]] = np.asarray(arr)[mask].copy()
        return out

    def _subset_flat(self, prefix: str, theta_s_deg: float, mode: str) -> Dict[str, np.ndarray]:
        theta_key = f"{prefix}_theta_s_deg"
        if theta_key not in self._npz:
            raise KeyError(f"Missing key in flat pool format: {theta_key}")
        mask = np.isclose(np.asarray(self._npz[theta_key], dtype=np.float64), theta_s_deg, atol=1e-9)
        out: Dict[str, np.ndarray] = {}
        stem = f"{prefix}_"
        for key, arr in self._npz.items():
            if key.startswith(stem):
                out[key[len(stem):]] = np.asarray(arr)[mask].copy()
        return out

    def _subset(self, prefix: str, theta_s_deg: float, mode: str) -> Dict[str, np.ndarray]:
        mode = str(mode)
        if mode not in ("full", "work"):
            raise ValueError("mode must be 'full' or 'work'")
        theta_s_deg = float(theta_s_deg)
        if mode == "full" and round(theta_s_deg, 12) not in self._full_set:
            raise KeyError(f"theta_s_deg={theta_s_deg} not found in full pool")
        if mode == "work" and round(theta_s_deg, 12) not in self._work_set:
            raise KeyError(f"theta_s_deg={theta_s_deg} not found in work pool")

        if self._format == "split":
            return self._subset_split(prefix, theta_s_deg, mode)
        return self._subset_flat(prefix, theta_s_deg, mode)

    def get_core_points(self, theta_s_deg: float, mode: str = "full") -> Dict[str, np.ndarray]:
        return self._subset("core", theta_s_deg, mode)

    def get_buffer_points(self, theta_s_deg: float, mode: str = "full") -> Dict[str, np.ndarray]:
        return self._subset("buffer", theta_s_deg, mode)

    def get_outer_points(self, theta_s_deg: float, mode: str = "full") -> Dict[str, np.ndarray]:
        return self._subset("outer", theta_s_deg, mode)


