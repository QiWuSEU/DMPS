def asdict(obj):
    """Small Python-3.6-compatible replacement for dataclasses.asdict()."""
    if hasattr(obj, "_asdict"):
        return dict(obj._asdict())
    if isinstance(obj, dict):
        return dict(obj)
    raise TypeError("asdict() expects one of this module's record objects")


