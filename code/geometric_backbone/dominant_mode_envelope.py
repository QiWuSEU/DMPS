#!/usr/bin/env python3
"""Evaluate the dominant IEP mode and its conservative core envelope.

This module supplies the |a0(theta)| factor used by geometric backbone
synthesis. It does not optimize ring geometry or modify the IEP spectrum.

Responsibilities
----------------
1) Load static point-pool data generated by geometric_sampling_pool.py
   (geometry + a0 interval descriptors only).
2) Build a theta-cache for |a0(theta)| using an external a0_abs callable.
3) Test monotone-decreasing behavior of |a0(theta)| on required intervals.
4) Build 1D core envelope values
       a0_max(alpha; theta_s) = max_{theta in [theta_min, theta_max]} |a0(theta)|
   using endpoint-max when monotone decreasing holds, otherwise sampled interval max.
5) Evaluate pointwise |a0(theta)| on 2D scout / tracking points.
6) Provide a unified 2D score helper: score = |a0| * |AF|.

This module intentionally does NOT:
- generate geometry pools
- read raw HFSS/IEP files directly
- execute dynamic tracking
- decide PSLL / optimization logic

It only bridges the static pool and the frozen iep_model.IEPModel.a0_abs
interface. Public class and function names are retained for compatibility.
"""

